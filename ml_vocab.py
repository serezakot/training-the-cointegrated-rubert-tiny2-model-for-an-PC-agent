def system_action_phrase(rng) -> str:
    """One OS/PC system action or file-management command (route='system', query=the command)."""
    kind = rng.choices(["action", "folder_op", "file_op", "dev", "pc_ctrl"], weights=[34, 24, 22, 10, 10])[0]
    if kind == "action":
        base = rng.choice(SYS_ACTIONS)
        if rng.random() < 0.25 and "комп" not in base and "пк" not in base and "ноутбук" not in base:
            return f"{base} {rng.choice(['на компьютере', 'на ноутбуке', 'на пк', 'сейчас'])}"
        return base
    if kind == "pc_ctrl":
        v = rng.choice(["выключи", "перезагрузи", "заблокируй", "отправь в сон", "усыпи"])
        dev = rng.choice(["компьютер", "комп", "пк", "ноутбук", "ноут", "систему"])
        tail = rng.choice(["", "сейчас", "быстро", "через пять минут", "через десять минут", "через полчаса", "через час"])
        return f"{v} {dev} {tail}".strip()
    if kind == "folder_op":
        s = rng.randrange(5)
        place = rng.choice(["", "на рабочем столе", "на диске д", "на диске с", "в документах", "в загрузках"])
        if s == 0:
            return f"создай {rng.choice(['папку', 'новую папку', 'каталог'])} {rng.choice(SYS_FOLDERS)} {place}".strip()
        if s == 1:
            return f"удали {rng.choice(['папку', 'каталог'])} {rng.choice(SYS_FOLDERS + ['старое', 'temp', 'лишнее', 'черновики', 'копии'])}"
        if s == 2:
            return f"переименуй папку {rng.choice(SYS_FOLDERS)} в {rng.choice(SYS_FOLDERS + ['архив', 'старое', 'работа', 'новое'])}"
        if s == 3:
            return f"скопируй папку {rng.choice(SYS_FOLDERS)} на {rng.choice(['флешку', 'рабочий стол', 'диск д'])}"
        return f"создай папку {rng.choice(['для фото', 'на рабочем столе', 'для отчётов', 'для проекта', 'на диске д', 'для сканов с работы'])}"
    if kind == "file_op":
        f = rng.choice(SYS_FILES)
        ext = rng.choice(SYS_FILE_KIND)
        fname = f"{f} {ext}".strip()
        s = rng.randrange(5)
        if s == 0:
            return f"{rng.choice(['удали', 'сохрани', 'распечатай', 'заархивируй'])} {rng.choice(['файл', 'документ'])} {fname}"
        if s == 1:
            return f"{rng.choice(['перенеси', 'перемести', 'скопируй'])} {rng.choice(['файл', 'документ'])} {fname} в папку {rng.choice(SYS_FOLDERS)}"
        if s == 2:
            return f"скопируй файл {fname} на {rng.choice(['рабочий стол', 'флешку', 'диск д'])}"
        if s == 3:
            return f"{rng.choice(['заархивируй', 'сожми', 'распакуй'])} папку {rng.choice(SYS_FOLDERS)}"
        return rng.choice(["удали последний файл", "распакуй архив в загрузки", "перенеси файлы в папку архив",
                           "скопируй папку на флешку"])
    return rng.choice(SYS_DEV)


